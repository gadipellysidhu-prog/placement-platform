// ─────────────────────────────── SQL generation ───────────────────────────────

const skillCols =
  'id, version, created_at, updated_at, name, category, verified, parent_category, subcategory, popularity_score, industry_tags, active, created_source';

let out = [];
out.push('-- Master Skills Catalog seed — generated by backend/scripts/generate-skills-seed.mjs.');
out.push('-- Idempotent: every insert is ON CONFLICT DO NOTHING, so re-running or pre-existing');
out.push('-- manually created skills (which keep their own metadata) are never disturbed.');
out.push('');

const seenNames = new Set();
const seenAliases = new Set();
let skillCount = 0;
let aliasCount = 0;
const aliasStatements = [];

for (const b of blocks) {
  out.push(`-- ── ${b.category} ${'─'.repeat(Math.max(4, 60 - b.category.length))}`);
  const rows = [];
  for (const [name, subcategory, aliases, popularity] of b.skills) {
    const nName = normalize(name);
    if (seenNames.has(nName)) {
      console.error(`DUPLICATE SKILL NAME, skipped: ${name}`);
      continue;
    }
    seenNames.add(nName);
    skillCount++;
    rows.push(
      `    (gen_random_uuid(), 0, now(), now(), '${esc(name)}', '${esc(b.category)}', TRUE, '${esc(b.parent)}', ` +
        `${subcategory ? `'${esc(subcategory)}'` : 'NULL'}, ${popularity}, '${esc(b.tag)}', TRUE, 'SEED')`,
    );

    // Aliases: explicit + auto-variants of the name (punctuation/space removal).
    const candidates = new Set(aliases);
    const noDots = name.replace(/\./g, '');
    const noSpaces = name.replace(/\s+/g, '');
    const spaced = name.replace(/[.\-]/g, ' ');
    for (const v of [noDots, noSpaces, spaced]) {
      if (normalize(v) !== nName) candidates.add(v);
    }
    for (const alias of candidates) {
      const nAlias = normalize(alias);
      if (!nAlias || nAlias === nName) continue;
      if (seenNames.has(nAlias) || seenAliases.has(nAlias)) continue; // name-lookup covers it / first wins
      seenAliases.add(nAlias);
      aliasCount++;
      aliasStatements.push(
        `INSERT INTO skill_aliases (id, version, created_at, updated_at, skill_id, alias, alias_normalized)\n` +
          `SELECT gen_random_uuid(), 0, now(), now(), s.id, '${esc(alias)}', '${esc(nAlias)}' FROM skills s WHERE s.name = '${esc(name)}'\n` +
          `ON CONFLICT (alias_normalized) DO NOTHING;`,
      );
    }
  }
  if (rows.length > 0) {
    out.push(`INSERT INTO skills (${skillCols}) VALUES`);
    out.push(rows.join(',\n') + '\nON CONFLICT (name) DO NOTHING;');
    out.push('');
  }
}

// Aliases must reject any normalized form that matches a *seeded* skill name; a second
// pass at SQL level guards against pre-existing rows too (alias vs live skills table).
out.push('-- ── Aliases ──────────────────────────────────────────────────────');
out.push(...aliasStatements);
out.push('');
out.push(`-- Totals: ${skillCount} skills, ${aliasCount} aliases.`);

console.log(out.join('\n'));
console.error(`Generated ${skillCount} skills and ${aliasCount} aliases.`);
